"""Isolated production-patch regression and relocated native pressure predicate.

Does not load an ASI, launch Driver.exe, attach to a game or touch game files.
The 108-byte predicate runs with all data/call references replaced by test mocks.
"""
import hashlib
import json
import re
import struct
import subprocess
import winreg
from pathlib import Path
from static_streaming_audit import DUMPBIN,PE
from audio_static_audit import EXPECTED

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'analysis/audio_default16m_r1_2026-11-05'
BUILD=ROOT/'build/audio_default_pool_test'

def main(output=OUT,build=BUILD,default64=False):
    OUT,BUILD=output,build
    OUT.mkdir(parents=True,exist_ok=True);BUILD.mkdir(parents=True,exist_ok=True)
    native=PE();assert hashlib.sha256(native.data).hexdigest()==EXPECTED
    code=native.read(0xC66530,0x6C)
    assert code[0:4]==bytes.fromhex('f30f1005')
    assert struct.unpack_from('<I',code,4)[0]==0xDD6414
    assert code[0x17]==0xE8 and 0xC66530+0x1C+struct.unpack_from('<i',code,0x18)[0]==0xC99B60
    assert struct.unpack_from('<I',code,0x35)[0]==struct.unpack_from('<I',code,0x45)[0]==0xDD6448
    assert native.read(0xDD6414,4)==struct.pack('<f',1.0)
    assert native.read(0xDD6448,4)==struct.pack('<f',4294967296.0)
    (ROOT/'tests/AudioPressurePredicateBytes.inc').write_text('// Exact C66530..C6659B; generated by test_audio_default_pool.py.\nstatic const U8 kNativePressureBytes[]={'+','.join('0x%02X'%v for v in code)+'};\n')
    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,r'SOFTWARE\Microsoft\Windows Kits\Installed Roots',0,winreg.KEY_READ|winreg.KEY_WOW64_32KEY) as key:
        sdk=Path(winreg.QueryValueEx(key,'KitsRoot10')[0])
    candidates=[v/'um/x86/kernel32.lib' for v in (sdk/'Lib').iterdir() if re.fullmatch(r'\d+(\.\d+)+',v.name)]
    library=max((v for v in candidates if v.is_file()),key=lambda v:tuple(map(int,v.parents[2].name.split('.'))))
    program=BUILD/'AudioDefaultPoolTest.exe'
    command=[str(DUMPBIN.with_name('cl.exe')),'/nologo','/O2','/Oi-','/GS-','/GR-','/Zl','/EHs-c-',
        '/Fo'+str(BUILD/'AudioDefaultPoolTest.obj'),str(ROOT/'tests/AudioDefaultPoolTest.cpp'),
        '/link','/NODEFAULTLIB','/ENTRY:AudioDefaultTestMain@0','/SUBSYSTEM:CONSOLE','/MACHINE:X86',
        '/OUT:'+str(program),str(library)]
    if default64:command.insert(1,'/DDSF_V29S_AUDIO_DEFAULT_64M=1')
    result=subprocess.run(command,cwd=BUILD,capture_output=True,text=True)
    (OUT/'pool_test_build.log').write_text(result.stdout+result.stderr)
    assert result.returncode==0,result.stdout+result.stderr
    run=subprocess.run([str(program)],capture_output=True,text=True,timeout=20)
    assert run.returncode==0,f'Check/exit {run.returncode}: {run.stdout!r} {run.stderr!r}'
    assert 'audio default-pool checks passed' in run.stdout,repr(run.stdout)
    summary=dict(result='passed',architecture='Win32',production_patch_sha256=hashlib.sha256((ROOT/'src/V29sAudioDefaultPoolPatch.inc').read_bytes()).hexdigest(),
        patch_scenarios=22 if default64 else 20,requested_bytes=67108864 if default64 else 16777216,
        native_predicate_cases=15,native_predicate_sha256=hashlib.sha256(code).hexdigest(),
        covers=['cold startup and phase-aware identity','only four operand bytes changed','unknown/missing baseline refused',
            'already initialized audio refused','threshold/code mismatch refused','late precommit changes refused',
            'protection/cache failures restore stock','failed rollback explicitly marked',
            'production integer pressure snapshot agrees with isolated native predicate, including unsigned and threshold boundaries',
            'run4188 observed usage triggers native pressure; same usage with expanded pool does not'],
        limitations='Patch OS calls fault-injected in fake memory. Isolated native predicate uses mocked pool stats. Full DllMain, real OS failures, playback and game behavior are not executed.')
    (OUT/'pool_tests.json').write_text(json.dumps(summary,indent=2));print(json.dumps(summary,indent=2))

if __name__=='__main__':main()
